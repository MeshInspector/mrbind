    inline bool KeyEquals(PyObject *key, const char *name)
    {
        return name[0] && PyUnicode_CompareWithASCIIString(key, name) == 0;
    }

    // Calls the first overload that accepts the arguments. Like pybind11, tries all overloads without implicit conversions first, then with them.
    inline PyObject *Dispatch(const Group &g, PyObject *self, PyObject *args, PyObject *kwargs)
    {
        constexpr int max_params = 64;
        PyObject *slots[max_params];
        Py_ssize_t num_pos = args ? PyTuple_Size(args) : 0;
        int first_pass = g.num_overloads > 1 ? 0 : 1;
        for (int pass = first_pass; pass < 2; pass++)
        {
            for (int i = 0; i < g.num_overloads; i++)
            {
                const Overload &ov = g.overloads[i];
                int base = g.has_self ? 1 : 0;
                if (num_pos + base > ov.num_params || ov.num_params > max_params)
                    continue;
                for (int j = 0; j < ov.num_params; j++)
                    slots[j] = nullptr;
                if (g.has_self)
                    slots[0] = self;
                for (Py_ssize_t j = 0; j < num_pos; j++)
                    slots[base + j] = PyTuple_GetItem(args, j);
                bool bad = false;
                if (kwargs)
                {
                    PyObject *key, *value;
                    Py_ssize_t pos = 0;
                    while (!bad && PyDict_Next(kwargs, &pos, &key, &value))
                    {
                        int found = -1;
                        for (int j = base; j < ov.num_params; j++)
                        {
                            if (KeyEquals(key, ov.names[j]))
                            {
                                found = j;
                                break;
                            }
                        }
                        if (found < 0 || slots[found])
                            bad = true;
                        else
                            slots[found] = value;
                    }
                }
                for (int j = 0; !bad && j < ov.num_required; j++)
                {
                    if (!slots[j])
                        bad = true;
                }
                if (bad)
                    continue;
                bool matched = false;
                PyObject *ret = ov.impl(slots, pass == 1, matched);
                if (matched)
                    return ret;
                if (PyErr_Occurred())
                    PyErr_Clear();
            }
        }
        return IncompatibleArguments(g, self, args, kwargs);
    }

