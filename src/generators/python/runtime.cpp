    inline void CallbackPostcall(void *, void *cleanup_value)
    {
        if (!cleanup_value)
            return;
        PyGILState_STATE gil = PyGILState_Ensure();
        Py_DECREF(reinterpret_cast<PyObject *>(cleanup_value));
        PyGILState_Release(gil);
    }

