    // Wraps a Python callable as the userdata of a C `std::function`.
    inline void CallableUserdataCallback(void **this_userdata, void *other_userdata)
    {
        PyGILState_STATE gil = PyGILState_Ensure();
        if (*this_userdata)
        {
            Py_DECREF(reinterpret_cast<PyObject *>(*this_userdata));
            *this_userdata = nullptr;
        }
        if (other_userdata)
        {
            Py_INCREF(reinterpret_cast<PyObject *>(other_userdata));
            *this_userdata = other_userdata;
        }
        PyGILState_Release(gil);
    }

